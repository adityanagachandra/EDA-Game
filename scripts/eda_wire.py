#!/usr/bin/env python3
"""
eda_wire.py, generate internal/generator/all/eda.go from the EDA generator packages on disk.

Every directory under internal/generator/eda/ except edakit is a domain package with a
Register(reg) function. The generated file imports each one and registers it, so adding a domain
never means editing all.go by hand.

Usage: python3 scripts/eda_wire.py [--only pkg1,pkg2,...]
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODULE = "github.com/chuma-beep/mathua"


def main(argv):
    base = os.path.join(ROOT, "internal", "generator", "eda")
    pkgs = sorted(d for d in os.listdir(base)
                  if d != "edakit" and os.path.isdir(os.path.join(base, d))
                  and any(f.endswith(".go") and not f.endswith("_test.go") for f in os.listdir(os.path.join(base, d))))
    if len(argv) == 2 and argv[0] == "--only":
        keep = set(argv[1].split(","))
        pkgs = [p for p in pkgs if p in keep]
    lines = [
        "// Code generated by scripts/eda_wire.py. DO NOT EDIT.",
        "",
        "package all",
        "",
        "import (",
        f'\t"{MODULE}/internal/generator"',
    ]
    lines += [f'\t"{MODULE}/internal/generator/eda/{p}"' for p in pkgs]
    lines += [
        ")",
        "",
        "// registerEDA adds every electronic-design-automation domain package to reg.",
        "func registerEDA(reg *generator.Registry) {",
    ]
    lines += [f"\t{p}.Register(reg)" for p in pkgs]
    lines += ["}", ""]
    with open(os.path.join(ROOT, "internal", "generator", "all", "eda.go"), "w") as f:
        f.write("\n".join(lines))
    print(f"OK: wired {len(pkgs)} EDA packages: {', '.join(pkgs)}")


if __name__ == "__main__":
    main(sys.argv[1:])
